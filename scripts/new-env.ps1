<#
.SYNOPSIS
  Creates infra\.env with freshly generated secrets. Refuses to overwrite an existing file,
  because a new MAILPULSE_ENCRYPTION_KEY would make all stored subjects and addresses unreadable.
.PARAMETER PublicBaseUrl
  Your Tailscale Funnel address, e.g. https://mypc.tail1234.ts.net. Read from Tailscale when omitted.
.PARAMETER EnvFile
  Where to write the file (default infra\.env).
#>
param(
    [string]$PublicBaseUrl = '',
    [string]$EnvFile = ''
)
$ErrorActionPreference = 'Stop'
$root = Split-Path $PSScriptRoot -Parent
if (-not $EnvFile) { $EnvFile = Join-Path $root 'infra\.env' }
if (Test-Path $EnvFile) {
    throw "$EnvFile already exists. It holds your encryption key; it is never overwritten. Delete it yourself only if you are starting from an empty database."
}

if (-not $PublicBaseUrl) {
    $tailscale = Join-Path $env:ProgramFiles 'Tailscale\tailscale.exe'
    if (Test-Path $tailscale) {
        $dnsName = (& $tailscale status --json | ConvertFrom-Json).Self.DNSName
        if ($dnsName) { $PublicBaseUrl = 'https://' + $dnsName.TrimEnd('.') }
    }
}
if (-not $PublicBaseUrl) {
    throw 'Could not read your Tailscale address. Run again with -PublicBaseUrl https://<pc>.<tailnet>.ts.net'
}
if ($PublicBaseUrl -notmatch '^https://[A-Za-z0-9.-]+$') {
    throw "PublicBaseUrl must look like https://host with no path or trailing slash (got '$PublicBaseUrl')"
}

function New-RandomBytes([int]$Count) {
    $bytes = New-Object byte[] $Count
    $rng = [System.Security.Cryptography.RandomNumberGenerator]::Create()
    try { $rng.GetBytes($bytes) } finally { $rng.Dispose() }
    return ,$bytes
}
function New-Hex([int]$Count) { return ([BitConverter]::ToString((New-RandomBytes $Count))).Replace('-', '').ToLowerInvariant() }
function New-Base64([int]$Count) { return [Convert]::ToBase64String((New-RandomBytes $Count)) }

$lines = @(
    '# Generated by scripts\new-env.ps1. Never commit this file.',
    '# Back up MAILPULSE_ENCRYPTION_KEY outside this PC (docs\SETUP.md section 4).',
    "MAILPULSE_DB_PASSWORD=$(New-Hex 24)",
    "MAILPULSE_ENCRYPTION_KEY=$(New-Base64 32)",
    "MAILPULSE_JWT_SECRET=$(New-Base64 48)",
    "MAILPULSE_SELF_SECRET=$(New-Hex 32)",
    "MAILPULSE_PUBLIC_BASE_URL=$PublicBaseUrl",
    "MAILPULSE_EXTENSION_ORIGINS=chrome-extension://pdinoocioohoejhjbeepjdadkkjldgeo",
    '# Free App ID from https://register.inboxsdk.com/ (docs\SETUP.md). Rebuild the extension after setting it.',
    'MAILPULSE_INBOXSDK_APP_ID='
)
New-Item -ItemType Directory -Force -Path (Split-Path $EnvFile -Parent) | Out-Null
[System.IO.File]::WriteAllText($EnvFile, ($lines -join "`n") + "`n")  # UTF-8 without BOM
Write-Host "Created $EnvFile"
Write-Host 'Next: back up MAILPULSE_ENCRYPTION_KEY outside this PC (docs\SETUP.md section 4), then run .\scripts\dev.ps1'
